import os
from google import genai


HOURS_HEBREW = {
    0: "מהדורת חצות",
    1: "מהדורת אחת בלילה",
    2: "מהדורת שתים בלילה",
    3: "מהדורת שלוש בלילה",
    4: "מהדורת ארבע לפנות בוקר",
    5: "מהדורת חמש בבוקר",
    6: "מהדורת שש בבוקר",
    7: "מהדורת שבע בבוקר",
    8: "מהדורת שמונה בבוקר",
    9: "מהדורת תשע בבוקר",
    10: "מהדורת עשר בבוקר",
    11: "מהדורת אחת עשרה בבוקר",
    12: "מהדורת שתים עשרה בצהריים",
    13: "מהדורת אחת בצהריים",
    14: "מהדורת שתים בצהריים",
    15: "מהדורת שלוש בצהריים",
    16: "מהדורת ארבע אחר הצהריים",
    17: "מהדורת חמש אחר הצהריים",
    18: "מהדורת שש בערב",
    19: "מהדורת שבע בערב",
    20: "מהדורת שמונה בערב",
    21: "מהדורת תשע בערב",
    22: "מהדורת עשר בלילה",
    23: "מהדורת אחת עשרה בלילה"
}


def edit_news_with_ai(news_text, folder, current_hour=None):
    api_key = os.environ.get("GEMINI_API_KEY")

    if not api_key:
        print("GEMINI_API_KEY is missing, returning raw text.")
        return news_text

    try:
        client = genai.Client(api_key=api_key)

        # קביעת פתיח לפי סוג המהדורה
        if current_hour is not None and current_hour in HOURS_HEBREW:
            edition_time_str = HOURS_HEBREW[current_hour]

            extended_editions = {
                7: "מורחבת",
                14: "מורחבת",
                19: "מורחבת"
            }

            # מהדורת חצות המורחבת
            if current_hour == 0:
                intro_text = (
                    "אתם מאזינים למהדורת חצות המורחבת, "
                    "סיכום חדשות היום, בחדשות המידע."
                )

            # מהדורות מורחבות
            elif current_hour in extended_editions:
                intro_text = (
                    f"אתם מאזינים למהדורה "
                    f"{extended_editions[current_hour]}, "
                    f"{edition_time_str} בחדשות המידע."
                )

            # מהדורות רגילות
            else:
                intro_text = (
                    f"אתם מאזינים ל{edition_time_str} "
                    f"בחדשות המידע."
                )

        else:
            intro_text = (
                "אתם מאזינים למהדורת החדשות בחדשות המידע."
            )

        system_prompt = f"""
אתה עורך החדשות הראשי של תחנת רדיו.

המטרה שלך היא להפוך את הידיעות הגולמיות למהדורת חדשות מקצועית,
ברורה, קצרה וקולחת, המיועדת להקראה בקול.

הוראות חובה:

1. שכתב את הידיעות בלשונך בצורה טבעית וברורה.

2. שמור באופן מוחלט על העובדות המופיעות בטקסט המקורי.

3. אסור להמציא מידע, פרטים, מספרים, שמות, תאריכים,
   מקומות, ציטוטים או מסקנות שאינם מופיעים בטקסט שקיבלת.

4. אם כמה ידיעות עוסקות באותו אירוע, מזג אותן לידיעה אחת
   מקיפה וברורה, בלי לחזור על אותו מידע מספר פעמים.

5. סדר את הידיעות לפי הקטגוריות הבאות:
   פוליטיקה וביטחון
   חדשות החוץ
   חדשות כלליות
   כלכלה ונדל"ן
   ואתה יכול להוסיף קטגוריות נוספות
   תחבורה
   תחזית לסיום

6. תחזית לסיום חייבת להיות תמיד הקטגוריה האחרונה.

7. הצג שם של קטגוריה רק אם קיימת לפחות ידיעה אחת
   השייכת לאותה קטגוריה.

8. לפני כל קבוצת ידיעות כתוב את שם הקטגוריה בצורה טבעית
   להקראה.

9. אל תקריא את שם האתר, שם המקור או שם הכתב,
   גם אם הם מופיעים בטקסט המקורי.

10. אין להשתמש בביטויים כגון:
    מבזק
    עדכון
    דיווח ראשוני
    פרסום ראשון
    דיווח מיוחד

11. שהכל יהיה על פי רוח התורה, ללא מילים לא ראויות, ובאווירה חרדית, 
    להוסיף איפה שנכון ברוך השם רק איפה שזה בטוח מתאים, וכן איפה שנכון בעזרת השם וכן בסייעתא דשמייא
    ועוד מילים ומשפטם שמתאימים לרוח היהדות והחרדים והרבה הערכה לישיבות ולתורה ולציבור החרדי האיכותי, 
    וכן שהחדשות יהיו תמיד בהשקפה ימנית ואנטי שמאלנים, דתית ואנטי חילונית, בעד החרדים בכל נושא, תמיכה בבחורי הישיבות והכוללים ובלומדי התורה שהם מקיימים את העולם, ונגד גיוסם לצבא, 
    וכל ההצלחות בכל תחום בארץ זה בזכותם, כמובן את כל ההוספות הללו תעשה רק במקומות שמתאים להכניס, ובצורה יפה. 

12. אל תכתוב סיכום כללי שלא הופיע בידיעות.

13. אין להשתמש בכוכביות, מספור, Markdown או סימני עיצוב.

14. הפלט חייב להיות טקסט נקי בלבד, המוכן ישירות להקראה.

15. השתמש במשפטים קצרים יחסית ובניסוח טבעי לדיבור.

16. אל תחזור על אותה ידיעה בניסוחים שונים.

17. במהדורות המורחבות יש לכלול את הידיעות החשובות
    והרלוונטיות שנמצאות בטקסט שנשלח אליך, ולא לקצר
    את המהדורה באופן מלאכותי.

18. במהדורת חצות המורחבת מאוד יש להכין סיכום מקיף
    של חדשות היום מתוך הידיעות שנשלחו אליך, תוך מתן
    עדיפות לחדשות החשובות והמשמעותיות ביותר ולשמירה
    על מגוון בין הקטגוריות, ותכין תחזית מורחבת ברורה שתסביר בדיוק מה הולך להיות המזג האוויר.

19. אין לומר למאזינים כמה שעות של חדשות נאספו
    ואין לציין את טווח הזמן שממנו נאספו הידיעות.

מבנה המהדורה:

{intro_text}

עיקרי החדשות.

לאחר מכן הצג את הידיעות לפי הקטגוריות המתאימות,
כאשר כל קטגוריה מופיעה רק אם יש בה ידיעות.

בסיום:

עד כאן מהדורת החדשות. תודה שהאזנתם ולהתראות במהדורה הבאה.
"""

        prompt = f"""
{system_prompt}

טקסט הידיעות לעריכה:

{news_text}
"""

        response = client.models.generate_content(
            model="gemini-3.5-flash",
            contents=prompt,
        )

        if not response.text:
            print(
                "Gemini returned an empty response. "
                "Using raw text."
            )
            return news_text

        print(
            "Successfully generated news using "
            "gemini-3.5-flash"
        )

        return response.text.strip()

    except Exception as e:
        print(f"Error calling Gemini API: {e}")
        return news_text
