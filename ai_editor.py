import os
from openai import OpenAI

def edit_news_with_ai(news_text, folder, current_hour=None):
    """
    מקבל חדשות גולמיות ומחזיר טקסט ערוך למהדורת חדשות
    """
    api_key = os.environ.get("OPENROUTER_API_KEY")

    if not api_key:
        raise Exception("Missing OPENROUTER_API_KEY")

    client = OpenAI(
        base_url="https://openrouter.ai/api/v1",
        api_key=api_key,
    )

    # הגדרת פתיח מותאם אישית לפי השעה עבור שלוחה 1
    intro_text = "אתם מאזינים למהדורת החדשות."
    if current_hour is not None:
        if 5 <= current_hour <= 8:
            intro_text = "אתם מאזינים למהדורת 06:00 בבוקר בחדשות המידע."
        elif 11 <= current_hour <= 14:
            intro_text = "אתם מאזינים למהדורת 12:00 בצהריים בחדשות המידע."
        elif 17 <= current_hour <= 20:
            intro_text = "אתם מאזינים למהדורת 06:00 בערב בחדשות המידע."
        elif current_hour >= 23 or current_hour <= 2:
            intro_text = "אתם מאזינים למהדורת 12:00 בלילה בחדשות המידע."

    prompt = f"""
אתה עורך חדשות מקצועי בתחנת רדיו.

קיבלת את כל הידיעות שפורסמו בשש השעות האחרונות.
המטרה שלך היא לשכתב ולערוך אותן למהדורת חדשות מקצועית, רהוטה וזורמת בעברית, בלשון שלך.

כללים מחייבים:
1. שכתב את הידיעות בלשונך המקצועית והברורה, אך שמור על כל העובדות והפרטים המקוריים.
2. אין להשמיט אף ידיעה ואין להוסיף מידע שלא מופיע בידיעות.
3. אם שתי ידיעות מדווחות על אותו אירוע – יש לאחד אותן לידיעה אחת מלאה.
4. לפני כל קטגוריה שקיימות בה ידיעות, יש לכתוב כותרת הקראה קצרה וברורה (לדוגמה: "חדשות פוליטיקה וביטחון", "חדשות חוץ", "חדשות כלכלה ונדלן", "תחבורה", "תחזית מזג האוויר").
5. אין להשתמש בנקודות, כוכביות, מקפים או סימני עיצוב מיותרים (הטקסט מיועד להקראה בלבד).
6. המעבר בין הנושאים צריך להיות טבעי וקלוח לקריינות.

סדר הקטגוריות במהדורה:
1. חדשות פוליטיקה וביטחון
2. חדשות חוץ
3. חדשות כלליות
4. כלכלה ונדל"ן
5. תחבורה
6. תחזית מזג האוויר

מבנה המהדורה:

אם מספר השלוחה הוא 1:

פתח בדיוק במילים אלו:
"{intro_text}
עיקרי החדשות מהשעות האחרונות."

לאחר מכן הצג את הקטגוריות והידיעות.

בסיום כתוב בדיוק:
"עד כאן מהדורת החדשות.
תודה שהאזנתם ולהתראות במהדורה הבאה."

אם מספר השלוחה אינו 1:

אין להוסיף פתיח.
אין להוסיף סיום.
יש להציג את כותרות הקטגוריות והידיעות בלבד.

מספר השלוחה:
{folder}

הידיעות לעריכה:

{news_text}
"""
    response = client.chat.completions.create(
        model="google/gemini-2.0-flash",
        messages=[
            {
                "role": "user",
                "content": prompt
            }
        ],
        temperature=0.2,
    )

    return response.choices[0].message.content.strip()
