import os
from openai import OpenAI

def edit_news_with_ai(news_text, folder, current_hour=None):
    """
    מקבל חדשות גולמיות ומחזיר טקסט ערוך למהדורת חדשות
    """
    api_key = os.environ.get("OPENROUTER_API_KEY")

    if not api_key:
        raise Exception("Missing OPENROUTER_API_KEY")

    client = OpenAI(
        base_url="https://openrouter.ai/api/v1",
        api_key=api_key,
    )

    # הגדרת פתיח מותאם אישית לפי השעה עבור שלוחה 1
    intro_text = "אתם מאזינים למהדורת החדשות."
    if current_hour is not None:
        if 5 <= current_hour <= 8:
            intro_text = "אתם מאזינים למהדורת 06:00 בבוקר בחדשות המידע."
        elif 11 <= current_hour <= 14:
            intro_text = "אתם מאזינים למהדורת 12:00 בצהריים בחדשות המידע."
        elif 17 <= current_hour <= 20:
            intro_text = "אתם מאזינים למהדורת 06:00 בערב בחדשות המידע."
        elif current_hour >= 23 or current_hour <= 2:
            intro_text = "אתם מאזינים למהדורת 12:00 בלילה בחדשות המידע."

    prompt = f"""
אתה עורך חדשות מקצועי בתחנת רדיו.

קיבלת את כל הידיעות שפורסמו בשש השעות האחרונות.
הידיעות כבר נאספו ממקורות חדשות אמינים.

המטרה שלך היא לערוך אותן למהדורת חדשות מקצועית, רהוטה וזורמת בעברית.

כללים מחייבים:
1. אין להוסיף שום מידע שלא מופיע בידיעות.
2. אין להמציא פרטים ואין לשנות עובדות.
3. אין להשמיט אף ידיעה.
4. אם שתי ידיעות מדווחות על אותו אירוע – יש לאחד אותן לידיעה אחת מלאה, תוך שמירה על כל הפרטים משתי הידיעות.
5. אין להזכיר שמות אתרי חדשות או מקורות.
6. אין להשתמש בנקודות, כוכביות, מקפים או סימני עיצוב מיותרים.
7. המעבר בין הנושאים צריך להיות טבעי וקלוח לקריינות.

סדר הידיעות במהדורה (יש לסדר בסדר זה בדיוק, במידה והידיעות קיימות):
1. חדשות פוליטיות וביטחוניות
2. חדשות חוץ
3. חדשות כלליות
4. כלכלה, נדל"ן ותחבורה
5. תחזית מזג האוויר לסיום

מבנה המהדורה:

אם מספר השלוחה הוא 1:

פתח בדיוק במילים אלו:
"{intro_text}
עיקרי החדשות מהשעות האחרונות."

לאחר מכן הצג את הידיעות המסודרות לפי הסדר לעיל.

בסיום כתוב בדיוק:
"עד כאן מהדורת החדשות.
תודה שהאזנתם ולהתראות במהדורה הבאה."

אם מספר השלוחה אינו 1:

אין להוסיף פתיח.
אין להוסיף סיום.
יש להציג רק את הידיעות עצמן בעברית תקינה וברורה.
אין לכתוב שום הסבר על העריכה ואין לציין את מספר השלוחה.

מספר השלוחה:
{folder}

הידיעות לעריכה:

{news_text}
"""
    response = client.chat.completions.create(
        model="google/gemini-2.0-flash-001",
        messages=[
            {
                "role": "user",
                "content": prompt
            }
        ],
        temperature=0.2,
    )

    return response.choices[0].message.content.strip()
