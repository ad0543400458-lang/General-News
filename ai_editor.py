import os
from openai import OpenAI


def edit_news_with_ai(news_text):
    """
    מקבל חדשות גולמיות ומחזיר טקסט ערוך למהדורת חדשות
    """

    api_key = os.environ.get("OPENROUTER_API_KEY")

    if not api_key:
        raise Exception("Missing OPENROUTER_API_KEY")

    client = OpenAI(
        base_url="https://openrouter.ai/api/v1",
        api_key=api_key,
    )

    prompt = f"""
אתה עורך חדשות מקצועי בתחנת רדיו.

קיבלת את כל הידיעות שפורסמו בשש השעות האחרונות.
הידיעות כבר נאספו ממקורות חדשות אמינים.

המטרה שלך היא לערוך אותן למהדורת חדשות מקצועית בעברית.

כללים מחייבים:

1. אין להוסיף שום מידע שלא מופיע בידיעות.
2. אין להמציא פרטים.
3. אין לשנות עובדות.
4. אין להשמיט אף ידיעה.
5. אם שתי ידיעות מדווחות על אותו אירוע – יש לאחד אותן לידיעה אחת מלאה, תוך שמירה על כל הפרטים משתי הידיעות.
6. אין להזכיר שמות אתרי חדשות או מקורות.
7. יש לסדר את הידיעות לפי נושאים כדי ליצור רצף הגיוני.
8. יש להשתמש בעברית תקינה, ברורה וטבעית המתאימה לקריין חדשות.
9. אין להשתמש בנקודות, כוכביות או סימני עיצוב מיותרים.
10. המעבר בין הנושאים צריך להיות טבעי.

מבנה המהדורה:

פתיח קצר ומכובד בסגנון:


להלן מהדורות השעות האחרונות."

לאחר מכן סדר את הידיעות לפי נושאים בצורה טבעית.

בסיום כתוב משפט סיום קצר ומכובד כגון:

"עד כאן מהדורת החדשות.
תודה שהאזנתם ולהתראות במהדורה הבאה."

הידיעות לעריכה:

{news_text}
"""
    response = client.chat.completions.create(
        model="openrouter/free",
        messages=[
            {
                "role": "user",
                "content": prompt
            }
        ],
        temperature=0.2,
    )

    return response.choices[0].message.content.strip()
