import os
from openai import OpenAI

def edit_news_with_ai(news_text, folder, current_hour=None):
    """
    מקבל חדשות גולמיות ומחזיר טקסט ערוך למהדורת חדשות
    """

    api_key = os.environ.get("OPENROUTER_API_KEY")

    if not api_key:
        raise Exception("Missing OPENROUTER_API_KEY")

    client = OpenAI(
        base_url="https://openrouter.ai/api/v1",
        api_key=api_key,
    )

    # פתיח מותאם אישית לשלוחה 1
    intro_text = "אתם מאזינים למהדורת החדשות."

    if current_hour is not None:
        if 5 <= current_hour <= 8:
            intro_text = "אתם מאזינים למהדורת 06:00 בבוקר בחדשות המידע."
        elif 11 <= current_hour <= 14:
            intro_text = "אתם מאזינים למהדורת 12:00 בצהריים בחדשות המידע."
        elif 17 <= current_hour <= 20:
            intro_text = "אתם מאזינים למהדורת 06:00 בערב בחדשות המידע."
        elif current_hour >= 23 or current_hour <= 2:
            intro_text = "אתם מאזינים למהדורת 12:00 בלילה בחדשות המידע."

    prompt = f"""
אתה עורך חדשות מקצועי בתחנת רדיו.

קיבלת אוסף של כל הידיעות שפורסמו במהלך שש השעות האחרונות.

מטרתך היא להכין מהדורת חדשות מקצועית, רהוטה, טבעית וזורמת להקראה.

המהדורה מיועדת לקריין ולכן כל הטקסט חייב להיות כתוב בצורה שנשמעת טבעית בהקראה.

כללים מחייבים:

1. שכתב את כל הידיעות בלשונך, אך שמור בקפדנות על כל העובדות.

2. אין להוסיף שום מידע שלא מופיע בידיעות המקור.

3. אין להשמיט עובדות חשובות.

4. כאשר קיימות מספר ידיעות על אותו אירוע,
יש למזג אותן לידיעה אחת מלאה,
לשלב את כל הפרטים הייחודיים,
ולהימנע לחלוטין מחזרות.

5. אין לקרוא שתי ידיעות שונות על אותו אירוע.

6. עליך לסווג בעצמך כל ידיעה לקטגוריה המתאימה ביותר לפי תוכנה.

7. הצג רק קטגוריות שקיימות בהן ידיעות.
אין ליצור כותרת ריקה.

8. סדר את הקטגוריות לפי הסדר הבא:

פוליטיקה וביטחון

חוץ

כללי

כלכלה ונדל"ן

תחבורה

מזג האוויר

9. בתוך כל קטגוריה סדר את הידיעות לפי חשיבותן לציבור,
ולא לפי סדר קבלתן.

10. לפני כל קטגוריה אמור רק את שם הקטגוריה.

לדוגמה:

פוליטיקה וביטחון

כלכלה ונדל"ן

תחבורה

מזג האוויר

ללא המילה "חדשות".

11. אין להזכיר את מקור הידיעה,
את שם האתר,
או את שם הכתב,
אלא אם הדבר הכרחי להבנת הידיעה.

12. יש להסיר ביטויים כגון:

מבזק

מבזק ראשון

עדכון

דיווח ראשוני

פורסם לראשונה

מתעדכן

ולנסח את הידיעה כאילו היא חלק ממהדורת חדשות רציפה.

13. כל ידיעה תהיה קצרה,
ברורה,
ותמציתית,
בדרך כלל בין משפט אחד לשלושה משפטים,
אלא אם האירוע מחייב פירוט נוסף.

14. המעבר בין הידיעות צריך להיות טבעי.

15. אין להשתמש בכוכביות.

16. אין להשתמש במקפים מיותרים.

17. אין להשתמש במספור.

18. אין להשתמש בנקודות מיותרות.

19. אין להשתמש בכותרות Markdown.

20. הפלט חייב להיות טקסט נקי בלבד.

מבנה המהדורה:

אם מספר השלוחה הוא 1:

פתח בדיוק במילים:

"{intro_text}

עיקרי החדשות מהשעות האחרונות."

לאחר מכן כתוב את הקטגוריות והידיעות.

בסיום כתוב בדיוק:

"עד כאן מהדורת החדשות.

תודה שהאזנתם ולהתראות במהדורה הבאה."

אם מספר השלוחה אינו 1:

אין להוסיף פתיח.

אין להוסיף סיום.

יש להציג רק את הקטגוריות שבהן קיימות ידיעות,
ולאחר כל קטגוריה את הידיעות המסודרות.

מספר השלוחה:

{folder}

הידיעות:

{news_text}
"""

    response = client.chat.completions.create(
        model="google/gemini-2.0-flash",
        messages=[
            {
                "role": "user",
                "content": prompt
            }
        ],
        temperature=0,
    )

    return response.choices[0].message.content.strip()

