import os
from openai import OpenAI


def edit_news_with_ai(news_text, folder, current_hour=None):
    """
    מקבל חדשות גולמיות ומחזיר טקסט ערוך למהדורת חדשות
    """

    api_key = os.environ.get("OPENROUTER_API_KEY")

    if not api_key:
        raise Exception("Missing OPENROUTER_API_KEY")

    client = OpenAI(
        base_url="https://openrouter.ai/api/v1",
        api_key=api_key,
    )

    # פתיח מותאם לשלוחה 1 לפי השעה
    intro_text = "אתם מאזינים למהדורת החדשות."

    if current_hour is not None:
        if 5 <= current_hour <= 8:
            intro_text = "אתם מאזינים למהדורת שש בבוקר בחדשות המידע."
        elif 11 <= current_hour <= 14:
            intro_text = "אתם מאזינים למהדורת שתים עשרה בצהריים בחדשות המידע."
        elif 17 <= current_hour <= 20:
            intro_text = "אתם מאזינים למהדורת שש בערב בחדשות המידע."
        elif current_hour >= 23 or current_hour <= 2:
            intro_text = "אתם מאזינים למהדורת חצות בחדשות המידע."

    system_prompt = f"""
אתה עורך חדשות מקצועי בתחנת רדיו.

קיבלת אוסף ידיעות שפורסמו במהלך שש השעות האחרונות.

המטרה:
להכין מהדורת חדשות מקצועית, זורמת וטבעית להקראה בקול.

הטקסט מיועד לקריין רדיו ולכן חובה לכתוב בשפה טבעית שמתאימה להקראה.

כללים מחייבים:

1. שכתב את הידיעות בלשונך תוך שמירה מלאה על העובדות.

2. אין להוסיף שום פרט שאינו מופיע בידיעות המקור.

3. אין להשמיט מידע חשוב.

4. אם קיימות מספר ידיעות על אותו אירוע:
   אחד אותן לידיעה אחת מלאה.
   שלב את הפרטים החשובים מכל המקורות.
   אל תחזור על אותו אירוע מספר פעמים.

5. אין ליצור רשימת מבזקים.
   התוצאה חייבת להישמע כמו מהדורת חדשות רציפה.

6. מיין את הידיעות לפי נושאים בעצמך.

7. השתמש רק בקטגוריות שיש בהן ידיעות.

סדר הקטגוריות:

פוליטיקה וביטחון

בחדשות החוץ

חדשות כלליות

בכלכלה ונדל"ן

בתחבורה

תחזית לסיום

8. לפני כל קטגוריה כתוב את שם הקטגוריה בצורה טבעית להקראה.

9. אין להציג אף ידיעה לפני שם קטגוריה.

10. הקטגוריה של מזג האוויר חייבת להיות תמיד האחרונה ולקרוא לה בדיוק:

תחזית לסיום

11. בתוך כל קטגוריה סדר לפי חשיבות לציבור.

12. אין להזכיר:
    מקורות,
    אתרי חדשות,
    שמות כתבים,
    או שמות עיתונאים,
    אלא אם הדבר הכרחי להבנת הידיעה.

13. הסר ניסוחים כגון:

מבזק

מבזק ראשון

דיווח ראשוני

פרסום ראשון

מתעדכן

עדכון

ונסח את הידיעה כחלק ממהדורה רגילה.

14. כל ידיעה תהיה קצרה וברורה.
    בדרך כלל משפט אחד עד שלושה משפטים.

15. המעבר בין הידיעות צריך להיות טבעי.

16. אין להשתמש בכוכביות.

17. אין להשתמש במספור.

18. אין להשתמש בכותרות Markdown.

19. אין להשתמש בסימני עיצוב מיוחדים.

20. הפלט חייב להיות טקסט נקי בלבד.

21. אין לעבור ידיעה ידיעה ולסכם כל אחת בנפרד.
    עליך לערוך את החומר כמהדורת חדשות אחת רציפה.

22. כאשר יש כמה ידיעות הקשורות לאותו נושא:
    שלב אותן באופן טבעי בתוך אותה ידיעה.

מבנה המהדורה:

אם מספר השלוחה הוא 1:

פתח בדיוק:

"{intro_text}

עיקרי החדשות מהשעות האחרונות."

לאחר מכן הצג את הקטגוריות והידיעות.

בסיום כתוב בדיוק:

"עד כאן מהדורת החדשות.

תודה שהאזנתם ולהתראות במהדורה הבאה."

אין להשמיט את הפתיח.

אין להשמיט את הסיום.

אין להשמיט את שמות הקטגוריות.

אם מספר השלוחה אינו 1:

אין להוסיף פתיח.

אין להוסיף סיום.

יש להציג רק את הקטגוריות שבהן קיימות ידיעות.

חובה עדיין להציג את שם הקטגוריה לפני הידיעות שלה.

מספר השלוחה:

{folder}

הידיעות הגולמיות:

{news_text}
"""

    response = client.chat.completions.create(
        model="google/gemini-3.6-flash",
        messages=[
            {
                "role": "user",
                "content": system_prompt,
            }
        ],
        temperature=0,
        max_tokens=2800,
    )

    return response.choices[0].message.content.strip()
