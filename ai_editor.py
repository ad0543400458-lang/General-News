        folder_num = str(folder).strip()

        if folder_num == "2":
            intro_text = "עדכוני השכונה."
            outro_text = "עד כאן עדכוני השכונה."
        elif folder_num == "3":
            intro_text = "עדכוני ירידות מחירי הדיור."
            outro_text = "עד כאן עדכוני הנדל\"ן והכלכלה."
