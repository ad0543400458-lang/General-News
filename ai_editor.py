import os
from google import genai


def edit_news_with_ai(news_text, folder, current_hour=None):
    """
    מקבל חדשות גולמיות ומחזיר טקסט ערוך למהדורת חדשות באמצעות Google Gemini API
    """

    # קריאת המפתח מתוך משתני הסביבה
    api_key = os.environ.get("GEMINI_API_KEY")

    if not api_key:
        raise Exception("המשתנה GEMINI_API_KEY אינו מוגדר במערכת")

    # יצירת הלקוח של Gemini
    client = genai.Client(api_key=api_key)

    intro_text = "אתם מאזינים למהדורת החדשות."

    if current_hour is not None:
        if 5 <= current_hour <= 8:
            intro_text = "אתם מאזינים למהדורת שש בבוקר בחדשות המידע."
        elif 11 <= current_hour <= 14:
            intro_text = "אתם מאזינים למהדורת שתים עשרה בצהריים בחדשות המידע."
        elif 17 <= current_hour <= 20:
            intro_text = "אתם מאזינים למהדורת שש בערב בחדשות המידע."
        elif current_hour >= 23 or current_hour <= 2:
            intro_text = "אתם מאזינים למהדורת חצות בחדשות המידע."

    system_prompt = f"""
אתה עורך החדשות הראשי של תחנת רדיו.
מטרתך להכין מהדורת חדשות מקצועית המיועדת לקריין.

יש לבצע את כל ההוראות הבאות ללא יוצא מן הכלל:
1. שכתב את הידיעות בלשונך תוך שמירה מלאה על כל העובדות.
2. אין להוסיף שום מידע שאינו מופיע בידיעות.
3. אין להשמיט מידע חשוב.
4. אם קיימות כמה ידיעות על אותו אירוע יש למזג אותן לידיעה אחת.
5. אין לחזור על אותו אירוע.
6. יש למיין את הידיעות לפי קטגוריות בסדר הבא:
   - פוליטיקה וביטחון
   - בחדשות החוץ
   - חדשות כלליות
   - בכלכלה ונדל"ן
   - בתחבורה
   - תחזית לסיום
7. חובה לכתוב את שם הקטגוריה בצורה טבעית להקראה לפני כל קבוצת ידיעות.
8. קטגוריית מזג האוויר תמיד תהיה אחרונה ותיקרא: "תחזית לסיום".
9. אין להציג אף ידיעה לפני שם קטגוריה.
10. אין ליצור כותרות ריקות.
11. סדר את הידיעות בתוך כל קטגוריה לפי חשיבות.
12. אין להזכיר מקורות, אתרי חדשות או שמות כתבים.
13. הסר מילים כגון: מבזק, עדכון, דיווח ראשוני, פרסום ראשון.
14. כתוב בשפה טבעית שמתאימה להקראה ברדיו.
15. אין להשתמש בכוכביות, מספור או כותרות Markdown. הפלט חייב להיות טקסט נקי בלבד.

אם מספר השלוחה הוא 1 חובה להחזיר בדיוק את המבנה הבא:
{intro_text}
עיקרי החדשות מהשעות האחרונות.
לאחר מכן כל הקטגוריות והידיעות.
בסיום חובה לכתוב:
עד כאן מהדורת החדשות.
תודה שהאזנתם ולהתראות במהדורה הבאה.

אם מספר השלוחה אינו 1:
אין פתיח ואין סיום, אך חובה לכתוב את שם הקטגוריה לפני כל קבוצת ידיעות.
"""

    user_prompt = f"""
מספר השלוחה: {folder}

ערוך את הידיעות למהדורת חדשות מלאה לפי כל ההוראות.

הידיעות:
{news_text}
"""

    # קריאה ל-API
    response = client.models.generate_content(
        model="gemini-2.5-flash",
        contents=[system_prompt, user_prompt],
    )

    return response.text.strip()
